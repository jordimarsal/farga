"""farga CLI — headless core. The skill and the future TUI are thin clients.

Commands map 1:1 to pipeline stages (S0-S6). Routing is never applied here:
`apply` delegates to `buildwright roles apply`, which owns the human gate.
Refusals exit 2 (buildwright convention); passthrough commands propagate rc.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

from farga import __version__
from farga.catalog import catalog_path, check_pieces, load_catalog
from farga.evidence import default_models
from farga.proposal import (
    parse_plus_lines,
    registry_ids,
    render_greenfield,
    validate_against,
)
from farga.scaffold import DEFAULT_INSTALLER, render_models_yaml, up
from farga.schema import (
    API_VERSION,
    ROLES,
    Architecture,
    Manifest,
    Tool,
    Workflow,
    load_manifest,
)

MANIFEST = "farga.yaml"
DEFAULT_BUILDWRIGHT = (
    Path.home() / "Documents" / "CV" / "projects" / "buildwright" / ".venv" / "bin" / "buildwright"
)

CONCEPT_TEMPLATE = """\
# {name} — concepte

> Origen: <draft o idea>. Status S0: concepte.

<Un paràgraf: què és, per a qui, quin buit tapa.>

## MVP

- <punt 1>
- <punt 2>
- <punt 3>

**Fora d'abast:** <…>
"""


def _buildwright_bin() -> str:
    env = os.environ.get("FARGA_BUILDWRIGHT_BIN")
    if env:
        return env
    which = shutil.which("buildwright")
    if which:
        return which
    return str(DEFAULT_BUILDWRIGHT)


def _clean_passthrough(tokens: list[str]) -> list[str]:
    """argparse REMAINDER keeps a leading '--' separator; buildwright does not want it."""
    return tokens[1:] if tokens and tokens[0] == "--" else tokens


def _manifest_or_refuse(path: Path | None) -> tuple[Path, Manifest]:
    target = path or Path(MANIFEST)
    if not target.is_file():
        print(
            f"refused: no {target} here — run `farga architect` or point --manifest at one",
            file=sys.stderr,
        )
        raise SystemExit(2)
    try:
        return target, load_manifest(target)
    except Exception as exc:
        print(f"refused: {target} is not a valid manifest: {exc}", file=sys.stderr)
        raise SystemExit(2) from exc


# ---------------------------------------------------------------- S0: new


def cmd_new(args: argparse.Namespace) -> int:
    project = Path(args.dir).expanduser().resolve()
    project.mkdir(parents=True, exist_ok=True)
    if not (project / ".git").exists():
        rc = subprocess.run(["git", "init", "-b", "main"], cwd=project, check=False).returncode
        if rc != 0:
            print("refused: git init failed", file=sys.stderr)
            return 2
    concept = project / "concept.md"
    if concept.is_file() and not args.force:
        print(f"refused: {concept} already exists (use --force to overwrite)", file=sys.stderr)
        return 2
    if args.concept_file:
        text = Path(args.concept_file).read_text(encoding="utf-8")
    else:
        text = CONCEPT_TEMPLATE.format(name=project.name)
    concept.write_text(text, encoding="utf-8")
    print(f"{project}: git repo + concept.md — next: fill it, then `farga architect`")
    return 0


# ---------------------------------------------------------------- S2: architect


def cmd_architect(args: argparse.Namespace) -> int:
    target = Path(args.manifest or MANIFEST)
    if target.is_file() and not args.force:
        print(f"refused: {target} exists (use --force to regenerate)", file=sys.stderr)
        return 2

    catalog = load_catalog(catalog_path(args.catalog))
    pieces, errs = [], []
    for spec in args.piece or []:
        piece_id, sep, role = spec.partition(":")
        if not sep or not role:
            errs.append(f"--piece expects id:role (saw '{spec}')")
            continue
        if piece_id not in catalog:
            errs.append(f"piece '{piece_id}' not in catalog {catalog_path(args.catalog)}")
            continue
        pieces.append((piece_id, role))

    preferred = args.preferred_model
    models = default_models(preferred)
    modules = [m.strip() for m in args.modules.split(",") if m.strip()] if args.modules else []

    body = f"""\
# farga.yaml — generated by `farga architect`; edit freely, then `farga validate`
apiVersion: {API_VERSION}

concept:
  file: concept.md
  profile: profile.md
  status: drafted

stack:
  tool: {args.tool}
  workflow: {args.workflow}
  architecture: {args.architecture}
  modules: [{", ".join(modules)}]

pieces:
"""
    for piece_id, role in pieces:
        body += f"  - id: {piece_id}\n    role: {role}\n"
    if not pieces:
        body += "  []  # ids de ~/.config/farga/peces.json\n"
    body += f"""
models:                      # BW_ROLE_PLANNER / WORKER / REVIEWER
  # S5: un servidor = un model; els rols d'un run son seqüencials -> mateix servidor.
  planner: {models.planner}
  worker: {models.worker}
  reviewer: {models.reviewer}
  alternatives:              # registrades per a propostes futures (S8)
"""
    for key, mid in models.alternatives.items():
        body += f"    {key}: {mid}\n"
    body += f"""
routing:
  source: debrief
  mode: propose-then-confirm
  proposal: .farga/proposal.txt

execution:
  runner: buildwright
  features_per_run: 2
  auto: false
  size: {args.size}

lanes:
  slots: 2
  servers: [llama8999]       # regla d'or: mai 8999+8080 alhora

observability:
  trace: langfuse
  evidence: harness/logs/
"""

    if errs:
        for err in errs:
            print(f"refused: {err}", file=sys.stderr)
        return 2

    # Validate before writing: the file we emit must load back cleanly.
    from farga.schema import Manifest

    m = Manifest.model_validate(yaml.safe_load(body))
    if check_pieces(m, catalog):
        print("refused: " + "; ".join(check_pieces(m, catalog)), file=sys.stderr)
        return 2

    target.write_text(body, encoding="utf-8")
    print(f"{target}: draft manifest (status drafted) — review, then `farga route`")
    return 0


# ---------------------------------------------------------------- validate


def cmd_validate(args: argparse.Namespace) -> int:
    target, manifest = _manifest_or_refuse(Path(args.manifest) if args.manifest else None)
    errors = check_pieces(manifest, load_catalog(catalog_path(args.catalog)))
    # Render check: every model the manifest mentions must have a wire (up fails otherwise).
    try:
        render_models_yaml(manifest)
    except Exception as exc:  # noqa: BLE001
        errors.append(str(exc))
    if errors:
        for err in errors:
            print(f"invalid: {err}", file=sys.stderr)
        return 2
    print(
        f"{target}: valid (status={manifest.concept.status.value}, "
        f"size={manifest.execution.size.value}, pieces={len(manifest.pieces)})"
    )
    return 0


# ---------------------------------------------------------------- S3: route


def cmd_route(args: argparse.Namespace) -> int:
    _, manifest = _manifest_or_refuse(Path(args.manifest) if args.manifest else None)
    proposal_path = Path(manifest.routing.proposal)

    if args.debrief:
        text = Path(args.debrief).read_text(encoding="utf-8")
        if not parse_plus_lines(text):
            print(
                f"refused: {args.debrief} has no '+ BW_ROLE_*' lines (debrief output?)",
                file=sys.stderr,
            )
            return 2
        text = (
            "# farga — proposta de debrief (routing_propose), verbatim\n" + text
            if not text.startswith("#")
            else text
        )
    else:
        text = render_greenfield(manifest.models, str(proposal_path))

    known = registry_ids(Path("models.yaml"))
    errors = validate_against(parse_plus_lines(text), known)
    if errors:
        for err in errors:
            print(f"refused: {err}", file=sys.stderr)
        return 2

    if args.dry_run:
        print(text, end="" if text.endswith("\n") else "\n")
        print(f"--- dry-run: {proposal_path} no escrit", file=sys.stderr)
        return 0

    proposal_path.parent.mkdir(parents=True, exist_ok=True)
    proposal_path.write_text(text, encoding="utf-8")
    apply_cmd = f"buildwright roles apply {proposal_path}"
    print(f"{proposal_path}: {len(parse_plus_lines(text))} canvi(s) — gate humà:")
    print(f"  {apply_cmd}   (o `farga apply`)")
    return 0


# ---------------------------------------------------------------- S4/S5: up


def cmd_up(args: argparse.Namespace) -> int:
    _, manifest = _manifest_or_refuse(Path(args.manifest) if args.manifest else None)
    installer = Path(args.installer) if args.installer else DEFAULT_INSTALLER
    if not installer.is_file():
        print(
            f"refused: harness installer not found at {installer} (--installer to set)",
            file=sys.stderr,
        )
        return 2
    try:
        plan = up(manifest, Path.cwd(), installer=installer, dry_run=args.dry_run)
    except Exception as exc:  # noqa: BLE001
        print(f"refused: {exc}", file=sys.stderr)
        return 2
    for line in plan:
        print(f"  {'[dry] ' if args.dry_run else '[ok]  '}{line}")
    return 0


# ---------------------------------------------------------------- S6: run / apply


def cmd_run(args: argparse.Namespace) -> int:
    _manifest_or_refuse(Path(args.manifest) if args.manifest else None)
    cmd = [_buildwright_bin(), "harness", "run", *_clean_passthrough(args.passthrough)]
    if args.yes:
        cmd.append("--yes")
    return subprocess.run(cmd, check=False).returncode


def cmd_apply(args: argparse.Namespace) -> int:
    _, manifest = _manifest_or_refuse(Path(args.manifest) if args.manifest else None)
    proposal_path = Path(manifest.routing.proposal)
    if not proposal_path.is_file():
        print(f"refused: {proposal_path} missing — run `farga route` first", file=sys.stderr)
        return 2
    cmd = [_buildwright_bin(), "roles", "apply", str(proposal_path)]
    if args.yes:
        cmd.append("--yes")
    return subprocess.run(cmd, check=False).returncode


# ---------------------------------------------------------------- status


def _gate_cmd(args: argparse.Namespace) -> int:
    """Gate passthrough (approve/reject/fix) with the SAME binary `run` uses —
    a 0.8.3 global buildwright has neither request_limit support nor current
    loop code; mixing binaries across gates and batches is how the S4 dispatch
    died with 'request_limit of 50'."""
    _manifest_or_refuse(Path(args.manifest) if args.manifest else None)
    cmd = [_buildwright_bin(), "harness", args.action, *args.comments]
    return subprocess.run(cmd, check=False).returncode


def cmd_status(args: argparse.Namespace) -> int:
    target, manifest = _manifest_or_refuse(Path(args.manifest) if args.manifest else None)
    print(
        f"manifest  {target} (status={manifest.concept.status.value}, "
        f"size={manifest.execution.size.value})"
    )
    print(
        f"stack     {manifest.stack.tool.value}/{manifest.stack.workflow.value}/"
        f"{manifest.stack.architecture.value} modules={manifest.stack.modules or '—'}"
    )
    print(f"pieces    {', '.join(p.id + ':' + p.role for p in manifest.pieces) or '—'}")
    for role in ROLES:
        print(f"model     {role:9s} -> {manifest.models.by_role(role)}")
    for key, mid in manifest.models.alternatives.items():
        print(f"model     alt:{key:12s} -> {mid}")

    env = Path(".env")
    if env.is_file():
        for line in env.read_text(encoding="utf-8").splitlines():
            if line.startswith("BW_ROLE_"):
                print(f".env      {line}")
    else:
        print(".env      — (cap routing aplicat; `farga route` + `farga apply`)")

    fl = Path("harness/feature_list.json")
    if fl.is_file():
        import json

        data = json.loads(fl.read_text(encoding="utf-8"))
        feats = data.get("features", data if isinstance(data, list) else [])
        counts: dict[str, int] = {}
        for f in feats:
            counts[f.get("status", "?")] = counts.get(f.get("status", "?"), 0) + 1
        print(f"features  {counts or '—'}")
    else:
        print("features  — (cap harness/feature_list.json: `farga up`)")

    for f in ("models.yaml", manifest.routing.proposal):
        mark = "ok " if Path(f).is_file() else "—  "
        print(f"file      {mark}{f}")
    return 0


# ---------------------------------------------------------------- parser


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="farga", description=__doc__.splitlines()[0])
    p.add_argument("--version", action="version", version=f"farga {__version__}")
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("new", help="S0: git repo + concept.md skeleton")
    s.add_argument("dir")
    s.add_argument("--concept-file", help="use this file as concept.md content")
    s.add_argument("--force", action="store_true")
    s.set_defaults(fn=cmd_new)

    s = sub.add_parser("architect", help="S2: draft farga.yaml from flags + catalog")
    s.add_argument("--manifest", help="path (default ./farga.yaml)")
    s.add_argument("--tool", default="opencode", choices=[t.value for t in Tool])
    s.add_argument("--workflow", default="hybrid", choices=[w.value for w in Workflow])
    s.add_argument(
        "--architecture", default="modular-monolith", choices=[a.value for a in Architecture]
    )
    s.add_argument("--modules", default="", help="comma-separated harness modules")
    s.add_argument("--piece", action="append", metavar="ID:ROLE", help="catalog piece (repeatable)")
    s.add_argument(
        "--preferred-model", default="local/gemma4", help="S5-collapsed model for every role"
    )
    s.add_argument("--size", default="M", choices=("S", "M", "L"))
    s.add_argument("--catalog")
    s.add_argument("--force", action="store_true")
    s.set_defaults(fn=cmd_architect)

    s = sub.add_parser("validate", help="schema + catalog + wires")
    s.add_argument("--manifest")
    s.add_argument("--catalog")
    s.set_defaults(fn=cmd_validate)

    s = sub.add_parser("route", help="S3: write .farga/proposal.txt (never applies)")
    s.add_argument("--manifest")
    s.add_argument(
        "--debrief", metavar="FILE", help="use a saved debrief routing.propose output verbatim"
    )
    s.add_argument("--dry-run", action="store_true")
    s.set_defaults(fn=cmd_route)

    s = sub.add_parser("up", help="S4/S5: scaffold (harness install + models.yaml + commit)")
    s.add_argument("--manifest")
    s.add_argument("--installer", help=f"harness install.sh (default {DEFAULT_INSTALLER})")
    s.add_argument("--dry-run", action="store_true")
    s.set_defaults(fn=cmd_up)

    s = sub.add_parser("run", help="S6: buildwright harness run (args passthrough)")
    s.add_argument("--manifest")
    s.add_argument(
        "--yes",
        "-y",
        action="store_true",
        help="forward --yes to buildwright (skips its interactive start prompt; "
        "human gates still park)",
    )
    s.add_argument(
        "passthrough", nargs=argparse.REMAINDER, help="args for `buildwright harness run`"
    )
    s.set_defaults(fn=cmd_run)

    s = sub.add_parser("apply", help="S3 gate: buildwright roles apply (delegates)")
    s.add_argument("--manifest")
    s.add_argument("--yes", action="store_true", help="skip buildwright's confirmation")
    s.set_defaults(fn=cmd_apply)

    s = sub.add_parser("gate", help="gate passthrough with the same binary `run` uses")
    s.add_argument("action", choices=("approve", "reject", "fix"))
    s.add_argument("comments", nargs="*", help="gate comments (reject/fix text)")
    s.add_argument("--manifest")
    s.set_defaults(fn=_gate_cmd)

    s = sub.add_parser("status", help="manifest + board + routing state")
    s.add_argument("--manifest")
    s.set_defaults(fn=cmd_status)

    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    rc: int = args.fn(args)
    return rc
